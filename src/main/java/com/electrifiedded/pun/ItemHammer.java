public class ItemHammer extends ItemSword {
   public ItemHammer() {
      super(PunMod.AOB);
      this.maxStackSize = 8;
      this.setMaxDamage(-1);
      this.setCreativeTab(PunMod.ThePunMod);
   }

   public void onUpdate(ItemStack stack, World world, Entity entity, int par4, boolean par5) {
      super.onUpdate(stack, world, entity, par4, par5);
      if (!(entity instanceof EntityPlayer)) return;
      EntityPlayer player = (EntityPlayer)entity;
      ItemStack equipped = player.getHeldItemMainhand();
      if (equipped == stack) {
         player.addPotionEffect(new PotionEffect(MobEffects.MINING_FATIGUE, 1, 3));
         player.addPotionEffect(new PotionEffect(MobEffects.SLOWNESS, 1, 0));
      }
   }

   public boolean hitEntity(ItemStack par1ItemStack, EntityLivingBase par2EntityLivingBase, EntityLivingBase par3EntityLivingBase) {
      Random rand = new Random();
      if (rand.nextInt(3) == 1) {
         par1ItemStack.shrink(1);
      }

      return true;
   }

   public ActionResult<ItemStack> onItemRightClick(World par2World, EntityPlayer par3EntityPlayer, EnumHand hand) {
      ItemStack par1ItemStack = par3EntityPlayer.getHeldItem(hand);
      EntityHammer hammer = new EntityHammer(par2World, par3EntityPlayer);
      par2World.spawnEntity(hammer);
      if (!par3EntityPlayer.capabilities.isCreativeMode) {
         par1ItemStack.shrink(1);
      }

      return new ActionResult<>(EnumActionResult.SUCCESS, par1ItemStack);
   }

   @SideOnly(Side.CLIENT)
   public void addInformation(ItemStack par1ItemStack, World worldIn, List<String> par3List, ITooltipFlag flagIn) {
      par3List.add(TextFormatting.GOLD + "No one likes hot ham in their face.");
   }
}
