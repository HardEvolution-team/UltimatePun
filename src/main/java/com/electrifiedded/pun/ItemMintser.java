public class ItemMintser extends ItemSword {
   public ItemMintser() {
      super(ToolMaterial.DIAMOND);
      this.setMaxStackSize(1);
      this.setCreativeTab(PunMod.ThePunMod);
      this.setMaxDamage(600);
   }

   public boolean hitEntity(ItemStack par1ItemStack, EntityLivingBase par2EntityLivingBase, EntityLivingBase par3EntityLivingBase) {
      par1ItemStack.damageItem(1, par3EntityLivingBase);
      par3EntityLivingBase.addPotionEffect(new PotionEffect(MobEffects.SPEED, 140, 2));
      LegacySounds.playSoundAtEntity(par3EntityLivingBase.world, par3EntityLivingBase, "random.fizz", 1.0F, 1.0F);
      return true;
   }

   @SideOnly(Side.CLIENT)
   public void addInformation(ItemStack par1ItemStack, World worldIn, List<String> par3List, ITooltipFlag flagIn) {
      par3List.add(TextFormatting.DARK_GREEN + "Works for mobs too");
      par3List.add(TextFormatting.GRAY + "Has " + (this.getMaxDamage() - this.getDamage(par1ItemStack)) + " uses left");
   }
}
