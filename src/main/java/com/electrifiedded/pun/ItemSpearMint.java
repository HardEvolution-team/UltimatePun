public class ItemSpearMint extends Item {
   public ItemSpearMint() {
      this.setCreativeTab(PunMod.ThePunMod);
      this.setMaxStackSize(8);
   }

   public ActionResult<ItemStack> onItemRightClick(World par2World, EntityPlayer par3EntityPlayer, EnumHand hand) {
      ItemStack par1ItemStack = par3EntityPlayer.getHeldItem(hand);
      EntitySpearMint spear = new EntitySpearMint(par2World, par3EntityPlayer, 1.2F);
      par2World.spawnEntity(spear);
      LegacySounds.playSoundAtEntity(par2World, par3EntityPlayer, "random.bow", 1.0F, 1.0F);
      if (!par3EntityPlayer.capabilities.isCreativeMode) {
         par1ItemStack.shrink(1);
      }

      return new ActionResult<>(EnumActionResult.SUCCESS, par1ItemStack);
   }

   @SideOnly(Side.CLIENT)
   public void addInformation(ItemStack par1ItemStack, World worldIn, List<String> par3List, ITooltipFlag flagIn) {
      par3List.add(TextFormatting.DARK_GREEN + "Smells Fresh");
   }
}
